import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
const dependencyRoot = process.env.WORK_CONTRACT_DEPS;
if (!dependencyRoot) throw new Error('WORK_CONTRACT_DEPS is required on the cloud runner');
const require = createRequire(resolve(dependencyRoot,'package.json'));
const solc = require('solc');
const ganache = require('ganache');
const { BrowserProvider, ContractFactory, id, keccak256, ZeroAddress } = require('ethers');
const source = readFileSync('contracts/DeHubWork.sol','utf8');
const mockToken = `pragma solidity ^0.8.20; import "@openzeppelin/contracts/token/ERC20/ERC20.sol";
contract MockWorkToken is ERC20 { constructor() ERC20("Work token","WORK") {} function mint(address to,uint256 amount) external { _mint(to,amount); } }`;
const output = JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources:{'DeHubWork.sol':{content:source},'MockWorkToken.sol':{content:mockToken}},
  settings:{optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'paris',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}}),
  {import:path=>({contents:readFileSync(resolve(dependencyRoot,'node_modules',path),'utf8')})}));
const errors = (output.errors || []).filter(e=>e.severity === 'error');
if (errors.length) throw new Error(errors.map(e=>e.formattedMessage).join('\n'));
const compiled = output.contracts['DeHubWork.sol'].DeHubWork;
const savedArtifact=JSON.parse(readFileSync('public/assets/work-escrow.json','utf8'));
assert.equal(savedArtifact.sourceHash,keccak256(new TextEncoder().encode(source)),'deployment artifact must match the reviewed contract');
assert.equal(savedArtifact.runtimeCodeHash,keccak256('0x'+compiled.evm.deployedBytecode.object));
const provider = new BrowserProvider(ganache.provider({logging:{quiet:true},wallet:{deterministic:true},chain:{hardfork:'shanghai'}}));
const [poster,worker,other,arbiter,treasury] = await Promise.all([0,1,2,3,4].map(i=>provider.getSigner(i)));
const tokenCode = output.contracts['MockWorkToken.sol'].MockWorkToken;
const token = await new ContractFactory(tokenCode.abi,tokenCode.evm.bytecode.object,poster).deploy();
await token.waitForDeployment();
const escrow = await new ContractFactory(compiled.abi,compiled.evm.bytecode.object,poster).deploy(await arbiter.getAddress(),await treasury.getAddress(),[await token.getAddress()]);
await escrow.waitForDeployment();
assert.equal(keccak256(await provider.getCode(await escrow.getAddress())),savedArtifact.runtimeCodeHash);
await (await token.mint(await poster.getAddress(),1000n)).wait();
await (await token.approve(await escrow.getAddress(),1000n)).wait();
const deadline = Number((await provider.getBlock('latest')).timestamp) + 3600;
await assert.rejects(escrow.createJob(await token.getAddress(),2,100n,2n,deadline));
await assert.rejects(escrow.createJob(await token.getAddress(),0,100n,1n,deadline-7200));
await (await escrow.createJob(await token.getAddress(),1,100n,3n,deadline)).wait();
const proof = id('clip-proof');
await assert.rejects(escrow.registerProof(1n,proof));
await (await escrow.connect(worker).registerProof(1n,proof)).wait();
await assert.rejects(escrow.cancelJob(1n));
await assert.rejects(escrow.approveSubmission(1n,await other.getAddress(),2n,proof,id('payment')));
await (await escrow.approveSubmission(1n,await worker.getAddress(),2n,proof,id('payment'))).wait();
assert.equal(await token.balanceOf(await worker.getAddress()),190n);
assert.equal(await token.balanceOf(await treasury.getAddress()),10n);
await assert.rejects(escrow.approveSubmission(1n,await worker.getAddress(),1n,proof,id('payment')));
await assert.rejects(escrow.connect(other).openDispute(1n));
await (await escrow.connect(worker).openDispute(1n)).wait();
await assert.rejects(escrow.connect(arbiter).adminResolve(1n,ZeroAddress,0n,90n,proof));
await (await escrow.connect(arbiter).adminResolve(1n,ZeroAddress,0n,100n,proof)).wait();
assert.equal(await token.balanceOf(await escrow.getAddress()),0n);
assert.equal(await token.balanceOf(await poster.getAddress()),800n);
await (await escrow.createJob(await token.getAddress(),2,500n,1n,deadline)).wait();
await assert.rejects(escrow.awardApplicant(2n,await poster.getAddress()));
await (await escrow.awardApplicant(2n,await worker.getAddress())).wait();
await assert.rejects(escrow.connect(other).registerProof(2n,id('contract-proof')));
await (await escrow.connect(worker).registerProof(2n,id('contract-proof'))).wait();
await (await escrow.connect(worker).openDispute(2n)).wait();
await assert.rejects(escrow.connect(other).adminResolve(2n,await worker.getAddress(),500n,0n,id('contract-proof')));
await (await escrow.connect(arbiter).adminResolve(2n,await worker.getAddress(),500n,0n,id('contract-proof'))).wait();
assert.equal(await token.balanceOf(await worker.getAddress()),665n);
assert.equal(await token.balanceOf(await escrow.getAddress()),0n);
mkdirSync('work-contract-artifact',{recursive:true});
writeFileSync('work-contract-artifact/escrow-artifact.json',JSON.stringify({abi:compiled.abi,bytecode:'0x'+compiled.evm.bytecode.object,
  runtimeCodeHash:keccak256('0x'+compiled.evm.deployedBytecode.object),sourceHash:keccak256(new TextEncoder().encode(source)),compiler:solc.version()},null,2)+'\n');
console.log('Escrow funding, proof eligibility, payout idempotency, fees, arbitration and full refunds passed.');
